export const PAPERTAB_CALLIGRAPHY_BOUNDS = {
  width: 440.3,
  height: 159.3,
};

/**
 * Generates an elegant, connected freehand calligraphy signature for "PaperTab"
 * with an artistic flourish underline.
 */
export function createPaperTabCalligraphyElements(options: CalligraphyOptions = {}): FreedrawElement[] {
  const scale = options.scale ?? 1.35;
  const targetW = PAPERTAB_CALLIGRAPHY_BOUNDS.width * scale;
  const targetH = PAPERTAB_CALLIGRAPHY_BOUNDS.height * scale;

  const screenW = typeof window !== 'undefined' ? window.innerWidth : 1920;
  const screenH = typeof window !== 'undefined' ? window.innerHeight : 1080;

  // Center horizontally, position slightly above middle (y = ~46%) so it looks balanced with widgets
  const targetCenterX = options.centerX ?? screenW / 2;
  const targetCenterY = options.centerY ?? screenH * 0.44;

  const startX = targetCenterX - targetW / 2;
  const startY = targetCenterY - targetH / 2;

  const groupId = newId();

  return RAW_STROKES.map((stroke) => {
    const isFlourish = stroke.name === 'flourish';
    const strokeColor = isFlourish
      ? options.flourishColor || '#6366f1'
      : options.primaryColor || (stroke.name.startsWith('P') || stroke.name.startsWith('T') ? '#818cf8' : '#a5b4fc');

    const scaledPoints: Point[] = stroke.points.map((p) => ({
      x: Math.round((startX + p.x * scale) * 10) / 10,
      y: Math.round((startY + p.y * scale) * 10) / 10,
    }));

    return {
      id: newId(),
      type: 'freedraw',
      strokeColor,
      fillColor: 'transparent',
      strokeWidth: Math.round(stroke.width * scale * 0.85 * 10) / 10,
      strokeStyle: 'solid',
      roughness: 0,
      opacity: 100,
      locked: false,
      groupIds: [groupId],
      points: scaledPoints,
      seed: randomSeed(),
    };
  });
}
