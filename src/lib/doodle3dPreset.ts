/**
 * Creates 3D hand-drawn sketchy block lettering for "PAPER TAB"
 * in the style of indie comic / street zine block doodle art (like "SHADY LANE").
 */
export function create3DBlockDoodleElements(options: Doodle3DOptions = {}): FreedrawElement[] {
  const scale = options.scale ?? 1.15;
  const isLight = options.isLightBg ?? false;

  const targetW = DOODLE_3D_BOUNDS.width * scale;
  const targetH = DOODLE_3D_BOUNDS.height * scale;

  const screenW = typeof window !== 'undefined' ? window.innerWidth : 1920;
  const screenH = typeof window !== 'undefined' ? window.innerHeight : 1080;

  const targetCenterX = options.centerX ?? screenW / 2;
  const targetCenterY = options.centerY ?? screenH * 0.44;

  const startX = targetCenterX - targetW / 2;
  const startY = targetCenterY - targetH / 2;

  const groupId = newId();

  // Colors based on light/dark mode
  const shadowColor = isLight ? '#4b5563' : '#64748b'; // dense scribble hatch
  const edgeColor = isLight ? '#1f2937' : '#94a3b8';   // 3D perspective edges
  const frontColor = isLight ? '#111827' : '#ffffff';  // front face outline

  const transformPoints = (raw: Point[][]): Point[][] => {
    return raw.map((stroke) =>
      stroke.map((p) => ({
        x: Math.round((startX + p.x * scale) * 10) / 10,
        y: Math.round((startY + p.y * scale) * 10) / 10,
      }))
    );
  };

  const results: FreedrawElement[] = [];

  // 1. Shadow scribble strokes (bottom layer)
  transformPoints(SHADOW_STROKES).forEach((pts) => {
    results.push({
      id: newId(),
      type: 'freedraw',
      strokeColor: shadowColor,
      fillColor: 'transparent',
      strokeWidth: Math.round(1.8 * scale * 10) / 10,
      strokeStyle: 'solid',
      roughness: 0,
      opacity: 85,
      locked: false,
      groupIds: [groupId],
      points: pts,
      seed: randomSeed(),
    });
  });

  // 2. 3D perspective side corner edges
  transformPoints(EDGE_STROKES).forEach((pts) => {
    results.push({
      id: newId(),
      type: 'freedraw',
      strokeColor: edgeColor,
      fillColor: 'transparent',
      strokeWidth: Math.round(2.4 * scale * 10) / 10,
      strokeStyle: 'solid',
      roughness: 0,
      opacity: 95,
      locked: false,
      groupIds: [groupId],
      points: pts,
      seed: randomSeed(),
    });
  });

  // 3. Front face outlines (top layer)
  transformPoints(FRONT_STROKES).forEach((pts) => {
    results.push({
      id: newId(),
      type: 'freedraw',
      strokeColor: frontColor,
      fillColor: 'transparent',
      strokeWidth: Math.round(3.0 * scale * 10) / 10,
      strokeStyle: 'solid',
      roughness: 0,
      opacity: 100,
      locked: false,
      groupIds: [groupId],
      points: pts,
      seed: randomSeed(),
    });
  });

  return results;
}
